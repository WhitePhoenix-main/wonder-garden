import { describe, expect, it } from 'vitest'
import { advance, basketCapacity, basketCount, initialState, oldestReadyPlot, saleValue, speciesInfo } from '../src/game'
import { createPersistence } from '../src/persistence/storage'
import { validState } from '../src/persistence/validation'
import { addLegacyFruit, cleanBed, commit, earn, legacySix, memoryStorage, plantAt, prepareFirstResearch, reject } from './helpers'

describe('Leafy and the market stall', () => {
  it('AT-01: charges once per level and starts a fresh 5/2/1-second interval', () => {
    const state = initialState(33)
    reject(state,{type:'upgradeHelper',target:1},'firstSale')
    reject(state,{type:'buyAutoSell'},'hireFirst')
    earn(state,25)
    reject(state,{type:'upgradeHelper',target:1},'noCoins')
    earn(state,2100)
    for (const [level,interval,price] of [[1,5,150],[2,2,450],[3,1,1200]] as const) {
      if (state.plots[12].plant?.lives===0) cleanBed(state,12)
      if (!state.plots[12].plant) commit(state,{type:'plant',plot:12,species:'radish'})
      // Keep a ready plant to verify the exact deadline independently of growth.
      Object.assign(plantAt(state,12),{progress:1,mature:true,readySince:state.playTime})
      const coins = state.coins
      commit(state,{type:'upgradeHelper',target:level})
      expect(state.coins).toBe(coins-price)
      expect(state.harvestRemaining).toBe(interval)
      expect(advance(state,interval-0.1)).not.toContain('Harvested')
      expect(advance(state,0.1).filter(e=>e==='Harvested')).toHaveLength(1)
      reject(state,{type:'upgradeHelper',target:level},'helperLevel')
    }
    reject(state,{type:'upgradeHelper',target:3},'helperLevel')
  })

  it('AT-02/03: ties break by index and idle or full turns are discarded', () => {
    const state = initialState(33)
    earn(state,150)
    commit(state,{type:'upgradeHelper',target:1})
    const helperEvents=(seconds:number)=>advance(state,seconds).filter(event=>event!=='MarketUpdated')
    expect(helperEvents(5)).toEqual([])
    advance(state,1)
    expect(oldestReadyPlot(state)).toBe(12)
    addLegacyFruit(state,basketCapacity(state))
    const plots=structuredClone(state.plots)
    expect(helperEvents(4)).toEqual([])
    expect(state.plots).toEqual(plots)
    expect(state.harvestRemaining).toBe(5)
    commit(state,{type:'sell'})
    expect(helperEvents(4.9)).toEqual([])
    expect(advance(state,0.1)).toContain('HelperHarvested:12')
    expect(advance(state,5)).toContain('HelperHarvested:13')
    expect(helperEvents(10)).toEqual(['PlantCleaned','PlantCleaned:12','PlantCleaned','PlantCleaned:13'])
    expect(helperEvents(5)).toEqual([])
  })

  it('HA-01/AT-05: manual and automatic harvest yield the same crop and cannot both collect it', () => {
    const automatic = initialState(33)
    earn(automatic,750)
    commit(automatic,{type:'compost',plot:12,expectedId:plantAt(automatic,12).id})
    commit(automatic,{type:'compost',plot:13,expectedId:plantAt(automatic,13).id})
    commit(automatic,{type:'plant',plot:8,species:'strawberry'})
    commit(automatic,{type:'plant',plot:9,species:'sunflower'})
    prepareFirstResearch(automatic)
    commit(automatic,{type:'compost',plot:5,expectedId:plantAt(automatic,5).id})
    advance(automatic,speciesInfo.sunflower.cycleSec)
    commit(automatic,{type:'upgradeHelper',target:1})
    advance(automatic,4.9)
    commit(automatic,{type:'harvest',plot:9})
    cleanBed(automatic,9)
    commit(automatic,{type:'sell'})
    const manual=structuredClone(automatic)
    const manualEvents=commit(manual,{type:'harvest',plot:8})
    expect(advance(manual,0.1)).toEqual([])
    expect(advance(automatic,0.1)).toEqual([...manualEvents,'HelperHarvested:8'])
    reject(automatic,{type:'harvest',plot:8},'notReady')
    expect(automatic.basket).toEqual(manual.basket)
    expect(automatic.basket[0].pollination?.result).toBe('solar_strawberry')
    expect(automatic.seeds).toEqual(manual.seeds)
    expect(automatic.revealed).toEqual([])
  })

  it('AT-02: an older ready plant on the higher index wins', () => {
    const state = initialState(33)
    earn(state,160)
    advance(state,6)
    commit(state,{type:'harvest',plot:12})
    cleanBed(state,12)
    commit(state,{type:'plant',plot:12,species:'radish'})
    advance(state,6)
    expect(plantAt(state,13).readySince!).toBeLessThan(plantAt(state,12).readySince!)
    commit(state,{type:'upgradeHelper',target:1})
    expect(advance(state,5)).toContain('HelperHarvested:13')
    expect(plantAt(state,12).progress).toBe(1)
  })

  it('preserves a rare plant on its last life during automatic harvest', () => {
    const state=initialState(33)
    earn(state,500)
    Object.assign(plantAt(state,12),{rarity:'rare',plus:['fruitful']})
    commit(state,{type:'upgradeHelper',target:1})
    commit(state,{type:'buyAutoSell'})
    advance(state,20)
    expect(state.plots[12].plant).toMatchObject({rarity:'rare',lives:1})
    expect(state.basket).toHaveLength(0)
    expect(state.seeds.radish).toBe(0)
  })

  it('AT-04: automatically sells on the deadline and resets it on manual sale', () => {
    const state=initialState(33)
    earn(state,500)
    commit(state,{type:'upgradeHelper',target:1})
    addLegacyFruit(state,15)
    const coins=state.coins
    expect(commit(state,{type:'buyAutoSell'})).toEqual(['AutoSellEnabled'])
    reject(state,{type:'buyAutoSell'},'alreadyAutomated')
    expect(state.coins).toBe(coins-300)
    expect(advance(state,9.9)).not.toContain('Sold')
    expect(advance(state,0.1)).toContain('Sold')
    expect(state.basket).toEqual([])
    addLegacyFruit(state,2)
    advance(state,4)
    expect(commit(state,{type:'sell'})).toEqual(['Sold'])
    expect(state.sellRemaining).toBe(10)
    addLegacyFruit(state,1)
    const after=state.coins
    expect(advance(state,9.9)).not.toContain('Sold')
    state.market.remaining=1
    const readyForSale=saleValue(state)
    expect(advance(state,0.1)).toEqual(['Sold'])
    expect(readyForSale).toBeGreaterThanOrEqual(3)
    expect(state.coins).toBe(after+readyForSale)
  })

  it('AT-04: filling the basket never sells during harvest, even at a shared helper and market deadline', () => {
    const state=initialState(33)
    earn(state,500)
    advance(state,6)
    commit(state,{type:'upgradeHelper',target:1})
    commit(state,{type:'buyAutoSell'})
    addLegacyFruit(state,basketCapacity(state)-2)
    plantAt(state,12).fruitRoll=0
    state.sellRemaining=state.harvestRemaining
    state.market.remaining=10
    const manual=structuredClone(state), before=state.coins
    expect(commit(manual,{type:'harvest',plot:12})).not.toContain('Sold')
    expect(basketCount(manual)).toBe(basketCapacity(manual))
    expect(manual.coins).toBe(before)
    const events=advance(state,5)
    expect(events.filter(e=>e==='Sold')).toHaveLength(1)
    expect(events).toContain('HelperHarvested:12')
    expect(state.coins).toBe(before+saleValue(manual))
    expect(state.sellRemaining).toBe(10)
  })

  it('SV-01: restores exact active deadlines and migrates schema 2 with automation unpurchased', () => {
    const state=initialState(33)
    earn(state,500)
    const store=memoryStorage()
    store.setItem('wonder-garden.save.v1',JSON.stringify({...legacySix(state),schemaVersion:2}))
    const storage=createPersistence(()=>store)
    expect(storage.load()).toMatchObject({coins:state.coins,helperLevel:0})
    commit(state,{type:'upgradeHelper',target:1})
    commit(state,{type:'buyAutoSell'})
    advance(state,9.6)
    storage.save(state)
    const copy=storage.load()
    expect(copy).toEqual(state)
    expect(advance(copy,0.3)).toEqual([])
    expect(advance(copy,0.1)).toContain('Harvested')
    advance(state,0.4)
    expect(copy.coins).toBe(state.coins)
    expect(copy.basket).toEqual(state.basket)
    expect(validState({...state,harvestRemaining:0})).toBe(false)
    expect(validState({...state,sellRemaining:11})).toBe(false)
    expect(validState({...state,helperLevel:0})).toBe(false)
    expect(validState({...state,autoSell:false})).toBe(false)
  })
})
